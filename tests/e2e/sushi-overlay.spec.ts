import { test, expect } from '@playwright/test'
import { openSettings } from './settings'

test('Sushi : ajouter un rectangle en teinte nommée au PDF importé', async ({ page }) => {
  await page.goto('/?tool=sushi')
  await expect(page.getByLabel('Largeur', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Placer le rectangle sur', { exact: true })).toHaveCount(0)
  await page.getByLabel('Choisir les fichiers').setInputFiles('apps/web/public/exemple-carte.pdf')
  await expect(page.getByLabel('Largeur', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Contour', { exact: true })).toHaveCount(0)
  await page.getByLabel('Placer le rectangle sur', { exact: true }).selectOption('trim')
  await page.getByLabel('Retrait intérieur', { exact: true }).fill('2')
  await openSettings(page, 'Tons directs')
  await page.getByLabel('Ton direct de découpe', { exact: true }).fill('DecoupeAtelier')
  await page.getByLabel('Épaisseur du trait', { exact: true }).fill('0.2')
  await expect(page.getByLabel('Ton direct de rainage', { exact: true })).toHaveCount(0)
  await expect(page.locator('canvas[data-ready=true]')).toBeVisible({ timeout: 20000 })
  const response = page.waitForResponse((r) => r.url().includes('/api/tools/sushi/run'))
  await page.getByRole('button', { name: 'Générer le fichier final', exact: true }).click()
  const result = await response
  expect(result.status(), await result.text()).toBe(201)
  const data = await result.json()
  expect(data.summary).toContain('DecoupeAtelier')
  expect(data.metrics['Rectangles de découpe']).toBe(2)
  const saved = await (
    await page.request.get(`/api/tool-jobs/${data.id}/files/reglages.json`)
  ).json()
  expect(saved.settings.pdf_inset).toBe(2)
  expect(saved.settings.cut_width).toBe(0.2)
  await expect(page.locator('canvas[data-ready=true]')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: /PDF avec contours de découpe/ }).click()
  expect((await download).suggestedFilename()).toBe('snackpress-contours.pdf')
  await page.screenshot({ path: 'test-results/sushi-overlay-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('tab', { name: 'Réglages', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/sushi-overlay-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Retirer le fichier 1', exact: true }).click()
  await expect(page.getByLabel('Largeur', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Placer le rectangle sur', { exact: true })).toHaveCount(0)
})
